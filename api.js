const timeseriesCache = {};
const CACHE_DURATION = 10 * 60 * 1000; // 10 minutes

async function fetchTimeseriesData(metal, timeframe) {
  const cacheKey = `${metal}-${timeframe}`;
  const cached = timeseriesCache[cacheKey];

  // return cached data if less than 10 minutes old
  if (cached && Date.now() - cached.timestamp < CACHE_DURATION) {
    console.log("using cache for:", cacheKey);
    return cached.data;
  }

  const now = new Date();
  const currentYear = now.getFullYear();
  const currentMonth = now.getMonth();

  let requests = [];

  if (timeframe === "YTD") {
    for (let m = 0; m <= currentMonth; m++) {
      const start = `${currentYear}-${String(m + 1).padStart(2, "0")}-01`;
      const lastDay = new Date(currentYear, m + 1, 0).getDate();
      const end = `${currentYear}-${String(m + 1).padStart(2, "0")}-${lastDay}`;
      requests.push(fetchHistoricalMetalData(metalToCode[metal], start, end));
    }
  }

  if (timeframe === "1M") {
    const start = new Date();
    start.setMonth(start.getMonth() - 1);
    requests.push(
      fetchHistoricalMetalData(
        metalToCode[metal],
        start.toISOString().split("T")[0],
        now.toISOString().split("T")[0],
      ),
    );
  }

  if (timeframe === "1W") {
    const start = new Date();
    start.setDate(start.getDate() - 7);
    requests.push(
      fetchHistoricalMetalData(
        metalToCode[metal],
        start.toISOString().split("T")[0],
        now.toISOString().split("T")[0],
      ),
    );
  }

  const results = await Promise.all(requests);

  // stitch all results together
  const labels = [];
  const values = [];

  results.forEach((data) => {
    if (!data.rates) return;
    const sorted = Object.entries(data.rates).sort(
      (a, b) => new Date(a[0]) - new Date(b[0]),
    );
    sorted.forEach(([date, row]) => {
      labels.push(date);
      values.push(row.metals[metal]);
    });
  });

  // store in cache with timestamp
  timeseriesCache[cacheKey] = {
    timestamp: Date.now(),
    data: { labels, values },
  };

  return { labels, values };
}

